"""Проверка ответов § 9 «Молекулярно-кинетическая теория газов» (задачи 9.1–9.33).

Каждая строка: номер, величина, наш расчёт, ответ книги. Пометки:
  «≠» — расхождение больше допуска (0,5 %): ошибка в книге или у нас, разбирать;
  «≈» — наш ответ, округлённый как в книге, отличается в последней цифре.
Постоянные — табл. 24: N_A = 6,02·10²³, k = 1,38·10⁻²³ Дж/К, R = 8,31, V_m = 22,4 л/моль; нормальные условия 273 К, 101,3 кПа.
Запуск:  python -X utf8 tools/check_mkt.py
"""
from math import sqrt, pi

NA, k, R, Vm = 6.02e23, 1.38e-23, 8.31, 22.4e-3
rows = []


def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-300):
        mark = '≠'
    else:
        s = f'{book:.6g}'
        mant = s.split('e')[0]
        dec = len(mant.split('.')[1]) if '.' in mant else 0
        exp = int(s.split('e')[1]) if 'e' in s else 0
        r = round(ours / 10**exp, dec) * 10**exp
        mark = ' ' if abs(r - book) <= 1e-9 * max(abs(book), 1e-300) else '≈'
    rows.append((no, what, ours, book, mark))


vkv = lambda T, M: sqrt(3 * R * T / M)
var = lambda T, M: sqrt(8 * R * T / (pi * M))
vv = lambda T, M: sqrt(2 * R * T / M)

# --- концентрация ---
chk('9.1', 'n', 1.44e18 / 12e-3, 1.2e20)
chk('9.2', 'V, л', 2.5e23 / 1.25e26 * 1e3, 2)
chk('9.3', 'n', 1.5e3 * NA / 20e-3, 4.52e28)
chk('9.4', 'n', NA / Vm, 2.69e25)
chk('9.5', 'm, г', 0.032 * 9.41e23 * 5e-3 / NA * 1e3, 0.25)
chk('9.6', 'n', 17.5e-3 / 0.028 * NA / 5e-3, 7.52e25)
chk('9.7', 'ν', 2e18 * 3e-3 / NA, 9.97e-9)
chk('9.8', 'n1/n2', 32 / 2, 16)
chk('9.9', 'Mr', 58.5e-3 * NA / (1e-3 * 2.2e26 * 5e-3), 32)
chk('9.10', 'NA', 1e-3 * 1.1e25 * 2e-3 * 32 / 1.17e-3, 6.02e23)
n11 = NA / Vm
chk('9.11', 'n1', n11, 2.69e25)
chk('9.11', 'n2', n11 * 0.6, 1.61e25)
chk('9.11', 'n3', 2 * n11 * 0.4, 2.15e25)

# --- основное уравнение, энергия ---
chk('9.12', 'n', 1e-3 / (k * 300), 2.42e17)
chk('9.13', '1) p, Па', 1e25 * k * 3, 414)
chk('9.13', '2) p, Па', 1e25 * k * 1e3, 138e3)
chk('9.14', 'N', 5e6 * 30e-3 / (k * 300), 3.62e25)
nu15 = 50e3 * 240e-6 / (R * 290)
chk('9.15', 'ν', nu15, 4.98e-3)
chk('9.15', 'n', 50e3 / (k * 290), 1.25e25)
chk('9.16', 'Δp', 1e20 / 100e-6 * k * 300, 4.14e3)
chk('9.17', 'ν', nu15, 4.97e-3)
chk('9.17', 'N', nu15 * NA, 2.99e21)
T18 = 1e-3 / (1e16 * k)
chk('9.18', 'T', T18, 7.25e3)
chk('9.18', 'εп', 1.5 * k * T18, 1.5e-19)
chk('9.19', 'εп', 1.5 * k * 600, 1.24e-20)
chk('9.19', 'ε (i = 6)', 3 * k * 600, 2.48e-20)
chk('9.19', 'W поступ.', 1.5 * R * 600 * 1e3, 7.48e6)
chk('9.19', 'W полн. (i = 6), как в книге', 3 * R * 600 * 1e3, 7.48e6)
chk('9.20', 'He', 1.5 * k * 400, 8.28e-21)
chk('9.20', 'O2', 2.5 * k * 400, 13.8e-21)
chk('9.20', 'H2O', 3 * k * 400, 16.6e-21)
chk('9.21', 'ε1', 0.5 * k * 1e3, 6.9e-21)
chk('9.21', 'εп', 1.5 * k * 1e3, 20.7e-21)
chk('9.21', 'εвр', k * 1e3, 13.8e-21)
chk('9.21', 'ε', 2.5 * k * 1e3, 34.5e-21)
chk('9.22', 'N', 0.13 * 1 / (k * 293), 3.22e19)
chk('9.23', 'Δp, Па', 3 * k * 600 / (1e-19 * 0.1), 2.48)
chk('9.24', 'T', 2 / 3 * 419e3 / R, 33.6e3)

# --- скорости ---
for no, T, b in ((1, 20, (500, 462, 407)), (2, 300, (1.94e3, 1.79e3, 1.58e3)), (3, 5e3, (7.90e3, 7.30e3, 6.48e3))):
    chk('9.25', f'{no}) vкв', vkv(T, 2e-3), b[0])
    chk('9.25', f'{no}) ⟨v⟩', var(T, 2e-3), b[1])
    chk('9.25', f'{no}) vв', vv(T, 2e-3), b[2])
chk('9.26', 'T', 11.2e3**2 * 4e-3 / (3 * R), 20.1e3)
chk('9.27', 'T', 100 * 32 / 2, 1.6e3)
chk('9.28', 'vкв', sqrt(3 * 200e3 * 4e-3 / 0.6e-3), 2e3)
chk('9.29', 'He vкв', vkv(1.2e3, 4e-3), 2.73e3)
chk('9.29', 'Ar vкв', vkv(1.2e3, 40e-3), 864)
chk('9.29', 'ε', 1.5 * k * 1.2e3, 2.48e-20)
chk('9.30', 'vкв, м/с', sqrt(3 * k * 300 / 1e-13), 352e-6)
chk('9.31', 'отношение', sqrt(1e-11 * NA / 0.032), 1.37e7)
chk('9.32', '⟨v⟩', 1e3 * sqrt(8 / (3 * pi)), 0.92e3)
chk('9.33', 'vв', vv(400, 2e-3), 1.82e3)

for no, what, ours, book, mark in rows:
    print(f'{mark} {no:5} {what:30} наш {ours:12.5g}   книга {book:.4g}')
print('\nрасхождений ≠:', sum(r[4] == '≠' for r in rows), ' в последней цифре ≈:', sum(r[4] == '≈' for r in rows), ' всего строк:', len(rows))
