def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-300):
        mark = '≠'
    else:
        s = f'{book:.6g}'
        mant = s.split('e')[0]
        dec = len(mant.split('.')[1]) if '.' in mant else 0
        e = int(s.split('e')[1]) if 'e' in s else 0
        r = round(ours / 10**e, dec) * 10**e
        mark = ' ' if abs(r - book) <= 1e-9 * max(abs(book), 1e-300) else '≈'
    rows.append((no, what, ours, book, mark))


def phi_seg(tau, p0, p1, A, n=20000):
    """Потенциал в точке A от отрезка p0–p1 (3D) с линейной плотностью tau — численно."""
    L = sqrt(sum((p1[i] - p0[i])**2 for i in range(3)))
    s = 0.0
    for k in range(n):
        t = (k + 0.5) / n
        x = [p0[i] + (p1[i] - p0[i]) * t for i in range(3)]
        s += K * tau * L / n / sqrt(sum((A[i] - x[i])**2 for i in range(3)))
    return s


def phi_arc(tau, R, A, th0, th1, n=20000):
    """Потенциал в точке A от дуги окружности радиуса R в плоскости z = 0 (центр в начале координат)."""
    s = 0.0
    for k in range(n):
        th = th0 + (th1 - th0) * (k + 0.5) / n
        x = (R * cos(th), R * sin(th), 0)
        s += K * tau * R * (th1 - th0) / n / sqrt(sum((A[i] - x[i])**2 for i in range(3)))
    return s


