"""Проверка ответов § 18 «Энергия заряженного проводника. Энергия электрического поля» (задачи 18.1–18.21).

Пометки: «≠» — расхождение больше допуска (0,5 %); «≈» — отличие в последней цифре.
ε0 = 8,85·10⁻¹² Ф/м; ε — табл. 17: слюда 7, фарфор 5, эбонит 3, парафин 2.
Энергии шаров (18.15–18.19) проверяются ещё и численным интегрированием w = ε0εE²/2 по объёму.
Запуск:  python -X utf8 tools/check_energiya_polya.py
"""
from math import pi, sqrt

EPS0 = 8.85e-12
K = 1 / (4 * pi * EPS0)
rows = []


def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-300):
        mark = '≠'
    else:
        s = f'{book:.6g}'
        mant = s.split('e')[0]
        dec = len(mant.split('.')[1]) if '.' in mant else 0
        e = int(s.split('e')[1]) if 'e' in s else 0
        r = round(ours / 10**e, dec) * 10**e
        mark = ' ' if abs(r - book) <= 1e-9 * max(abs(book), 1e-300) else '≈'
    rows.append((no, what, ours, book, mark))


def shell_energy(Efun, epsfun, r1, r2, n=200000):
    s = 0.0
    for k in range(n):
        r = r1 + (r2 - r1) * (k + 0.5) / n
        s += 0.5 * EPS0 * epsfun(r) * Efun(r)**2 * 4 * pi * r * r * (r2 - r1) / n
    return s


chk('18.1', 'W, пДж (в книге «мкДж»)', (1e-12)**2 / (2 * 10e-12) * 1e12, 0.05)
chk('18.2', 'W, мкДж', 10e-9 * 6e3 / 2 * 1e6, 30)
chk('18.2', 'F, мН (в книге 15)', 10e-9 * 6e3 / (2 * 0.02) * 1e3, 15)
C = 7 * EPS0 * 0.03 / 1e-3
chk('18.3', 'Q, Дж', C * 15e3**2 / 2, 0.209)
chk('18.4', 'w, Дж/м³', 0.05 / 0.02, 2.5)
C1 = EPS0 * pi * 0.1**2 / 0.01
chk('18.5', 'A, мкДж', C1 * 1.2e3**2 / 2 * (3.5 / 1 - 1) * 1e6, 50)
chk('18.6', "U', В", 300 * 5, 1500)
chk('18.6', 'A, мДж', 1.11e-9 * 300**2 / 2 * 4 * 1e3, 0.2)
chk('18.7', 'W искры, мДж', 600e-12 * 400e-12 / 1000e-12 * 1.5e3**2 / 2 * 1e3, 0.27)
C = 1 / (1 + 1 / 2 + 1 / 3) * 1e-6
Q = C * 1.1e3
for c, b in [(1, 0.18), (2, 0.09), (3, 0.06)]:
    chk('18.8', f'посл., W при C = {c} мкФ, Дж', Q**2 / (2 * c * 1e-6), b)
for c, b in [(1, 0.605), (2, 1.121), (3, 1.82)]:
    chk('18.8', f'пар., W при C = {c} мкФ, Дж', c * 1e-6 * 1.1e3**2 / 2, b)
chk('18.9', 'A, мкДж', 111e-12 * 600**2 / 2 * (5 - 1) * 1e6, 80)
sig, V, eps = 8.85e-9, 1e-4, 5
chk('18.10', 'A, нДж (в книге 63,5)', sig**2 / (2 * EPS0) * (1 - 1 / eps) * V * 1e9, 63.5)
chk('18.10', 'по формуле книги, нДж', 0.5 * sig**2 / EPS0 * (eps - 1) / eps * (2 * eps - 1) / eps * V * 1e9, 63.5)
eps = 3
chk('18.11', "σ', нКл/м²", EPS0 * 1e3 * (eps - 1) / eps * 1e9, 5.9, 0.01)
chk('18.11', 'W, пДж', 0.5 * EPS0 * 1e6 / eps * 0.03 * 2e-3 * 1e12, 88.5)
chk('18.12', 'W, пДж', 0.5 * EPS0 * 1e6 * ((eps - 1) / eps)**2 * 0.03 * 2e-3 * 1e12, 118)
chk('18.13', 'W, мкДж', 0.5 * 4 * pi * EPS0 * 0.04 * 500**2 * 1e6, 0.55, 0.02)
chk('18.14', 'W, мкДж', K * (100e-9)**2 / (2 * 0.1) * 1e6, 450)
R = 10e-12 / (4 * pi * EPS0)
Q = 10e-12 * 3e3
chk('18.15', 'W, мкДж', 0.5 * 10e-12 * 3e3**2 * (1 - 1 / 3) * 1e6, 30)
chk('18.15', 'W численно, мкДж', shell_energy(lambda r: K * Q / r**2, lambda r: 1, R, 3 * R) * 1e6, 30)
chk('18.16', 'W, мкДж', (0.1e-6)**2 / (16 * pi * EPS0 * 0.1) * 1e6, 225)
chk('18.17', 'R₂, см', 2 * 6, 12)
rho, R, eps = 10e-9, 0.1, 2
W1 = 2 * pi / 45 * rho**2 / (EPS0 * eps) * R**5
W2 = 2 * pi / 9 * rho**2 / EPS0 * R**5
chk('18.18', 'W₁, пДж (в книге «нДж»)', W1 * 1e12, 7.88, 0.01)
chk('18.18', 'W₂, пДж (в книге «нДж»)', W2 * 1e12, 78.8, 0.01)
Qb = 4 / 3 * pi * R**3 * rho
chk('18.18', 'W₁ численно, пДж', shell_energy(lambda r: rho * r / (3 * EPS0 * eps), lambda r: eps, 0, R) * 1e12, 7.88, 0.01)
chk('18.18', 'W₂ численно, пДж', shell_energy(lambda r: K * Qb / r**2, lambda r: 1, R, 2000 * R) * 1e12, 78.8, 0.01)
chk('18.19', 'W_вне/W_внутри (эбонит)', 5 * 3, 15)
chk('18.20', 'Π, мкДж', K * (0.6 * 4e-18 / 0.04 + 0.6 * 9e-18 / 0.06 + 6e-18 / 0.2) * 1e6, 1.62)
chk('18.21', 'v, м/с', 3e-6 / sqrt(4 * pi * EPS0 * 0.01 * 0.1), 9, 0.01)
chk('18.21', 'по формуле книги (2πε₀), м/с', 3e-6 / sqrt(2 * pi * EPS0 * 0.01 * 0.1), 9, 0.01)

for no, what, ours, book, mark in rows:
    print(f'{mark} {no:6} {what:40} наш {ours:12.5g}   книга {book:g}')
print(f'\nрасхождений ≠: {sum(r[4] == "≠" for r in rows)}  в последней цифре ≈: {sum(r[4] == "≈" for r in rows)}  всего строк: {len(rows)}')
