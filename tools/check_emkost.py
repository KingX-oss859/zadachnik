chk('17.24', 'C, пФ (баланс)', ser(1, 2) + ser(2, 4), 2)
chk('17.24', 'C, пФ (узловые потенциалы)', bridge(1, 2, 2, 4, 3), 2)
chk('17.25', 'C₄, пФ', 12 * 6 / 8, 9)
chk('17.25', 'C при C₅ = 1 и 100 пФ одинакова (разность)', bridge(8, 12, 6, 9, 1) - bridge(8, 12, 6, 9, 100) + 1, 1)

