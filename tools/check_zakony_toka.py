rows = []


def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-300):
        mark = '≠'
    else:
        s = f'{book:.6g}'
        mant = s.split('e')[0]
        dec = len(mant.split('.')[1]) if '.' in mant else 0
        e = int(s.split('e')[1]) if 'e' in s else 0
        r = round(ours / 10**e, dec) * 10**e
        mark = ' ' if abs(r - book) <= 1e-9 * max(abs(book), 1e-300) else '≈'
    rows.append((no, what, ours, book, mark))


def solve(A, b):
    n = len(b)
    M = [row[:] + [b[i]] for i, row in enumerate(A)]
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(M[r][c]))
        M[c], M[p] = M[p], M[c]
        for r in range(n):
            if r != c:
                f = M[r][c] / M[c][c]
                M[r] = [M[r][k] - f * M[c][k] for k in range(n + 1)]
    return [M[i][n] / M[i][i] for i in range(n)]


def cube(a, b):
    """Сопротивление куба из единичных рёбер между вершинами a и b (вершины — тройки 0/1)."""
    V = list(product((0, 1), repeat=3))
    idx = {v: i for i, v in enumerate(V)}
    n = len(V)
    G = [[0.0] * n for _ in range(n)]
    for v in V:
        for k in range(3):
            w = list(v); w[k] ^= 1; w = tuple(w)
            G[idx[v]][idx[v]] += 1
            G[idx[v]][idx[w]] -= 1
    # потенциал b = 0: вычёркиваем b; в a втекает ток 1
    keep = [i for i in range(n) if i != idx[b]]
    A = [[G[i][j] for j in keep] for i in keep]
    rhs = [1.0 if i == idx[a] else 0.0 for i in keep]
    phi = solve(A, rhs)
    return phi[keep.index(idx[a])]


def two_node(branches):
    """Ветви между узлами L и R: (ЭДС, повышающая потенциал от L к R; сопротивление).
    Возвращает V = φR − φL и токи ветвей от L к R."""
    V = sum(E / r for E, r in branches) / sum(1 / r for E, r in branches)
    return V, [(E - V) / r for E, r in branches]


