"""Проверка ответов § 33 «Оптика движущихся тел» (33.1–33.21).

Пометки: «≠» — расхождение больше допуска (0,5 %); «≈» — отличие в последней цифре.
c = 3·10⁸ м/с; R = 8,31 Дж/(моль·К); R_Солнца = 6,95·10⁸ м; E0(e) = 0,511 МэВ;
m_μ c² = 106 МэВ, m_π c² = 140 МэВ.
Запуск:  python -X utf8 tools/check_optika_dvizh.py
"""
from math import pi, sqrt, sin, cos, radians

MU0 = 4 * pi * 1e-7
E = 1.60e-19
ME = 9.11e-31
K = 8.99e9
rows = []


def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-300):
        mark = '≠'
    else:
        s = f'{book:.6g}'
        mant = s.split('e')[0]
        dec = len(mant.split('.')[1]) if '.' in mant else 0
        e = int(s.split('e')[1]) if 'e' in s else 0
        r = round(ours / 10**e, dec) * 10**e
        mark = ' ' if abs(r - book) <= 1e-9 * max(abs(book), 1e-300) else '≈'
    rows.append((no, what, ours, book, mark))


from math import acos, degrees
C, RG = 3e8, 8.31
chk('33.1', 'β', sqrt(1 - 0.99**2), 0.141)
chk('33.2', 'ω, 10⁻⁶ рад/с', 1.5e-5 * C / (2 * 6.95e8) / 1e-6, 3.2, 0.02)
chk('33.3', 'Δν, кГц (в книге 10)', 30e6 * 1e4 / C / 1e3, 10)
chk('33.4', 'v, Мм/с', C * 2.5 / 656.3 / 1e6, 1.1, 0.05)
chk('33.5', 'Δλ/λ, 10⁻⁵', 2 / C * sqrt(3 * RG * 300 / 1e-3) / 1e-5, 1.8, 0.02)
chk('33.6', '1) Δν/ν, 10⁻⁶', 2 / C * sqrt(3 * RG * 290 / 0.059) / 1e-6, 2.3, 0.02)
chk('33.6', '2) Δν/ν, 10⁻⁴', 2 / C * sqrt(3 * RG * 1e7 / 0.059) / 1e-4, 4.3, 0.02)
for k, u, nb in (('1)', 20e3, 1000067), ('2)', -20e3, 999933), ('3)', 4e3, 1000013), ('4)', -4e3, 999987)):
    chk('33.7', f'{k} ν, Гц', 1e6 * (1 + u / C), nb, 1e-6)
chk('33.8', '|Δλ|, пм', 2 * 10 * 670 / C * 600e-9 * 1e12, 26.8)
chk('33.9', '1) λ, нм', 500 * 1.2 / 0.8, 750)
chk('33.9', '2) λ, нм (в книге 600,03)', 500 * (1 + 2 * 9e3 / C), 600.03, 1e-6)
chk('33.10', 'v, км/с', 4e3 / 600e6 * C / 2 / 1e3, 1)
chk('33.11', 'v, 10⁴ км/с', (650**2 - 550**2) / (650**2 + 550**2) * C / 1e7, 5, 0.01)
chk('33.12', 'β', (1 - 0.25) / (1 + 0.25), 0.6)
chk('33.13', 'β', (760**2 - 410**2) / (760**2 + 410**2), 0.549)
f = lambda th: 4 * sqrt(1 - 0.36) / (1 + 0.6 * cos(radians(th)))
chk('33.14', 'ν1 (θ = 120°), ГГц', f(120), 4.57)
chk('33.14', 'ν2 (θ = 60°), ГГц', f(60), 2.46)
chk('33.15', 'v, 10⁸ м/с (в книге «1,88 м/с»)', C / 1.6 / 1e8, 1.88)
chk('33.16', 'β', 1 / (1.8 * cos(radians(20))), 0.591)
chk('33.17', 'U_min, кВ', 511 * (1.5 / sqrt(1.5**2 - 1) - 1), 175)
n = 1.00029
chk('33.18', 'T_min, МэВ (в книге 29,5)', 0.511 * (n / sqrt(n**2 - 1) - 1), 29.5)
g = 1 + 0.51 / 0.511
