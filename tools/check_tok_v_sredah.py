"""Проверка ответов § 20 «Ток в металлах, жидкостях и газах» (задачи 20.1–20.32).

Пометки: «≠» — расхождение больше допуска (0,5 %); «≈» — отличие в последней цифре.
e = 1,60·10⁻¹⁹ Кл; mₑ = 9,11·10⁻³¹ кг; k = 1,38·10⁻²³ Дж/К; N_A = 6,02·10²³ моль⁻¹; F = 9,65·10⁴ Кл/моль.
Табл. 9 и 18: медь — плотность 8,93 г/см³, ρ = 17 нОм·м; алюминий — 2,70 г/см³.
Молярные массы округлены, как в книге: Cu 64, Al 27, Zn 65,4, Fe 56 г/моль.
Запуск:  python -X utf8 tools/check_tok_v_sredah.py
"""
from math import sqrt

E = 1.60e-19
ME = 9.11e-31
KB = 1.38e-23
NA = 6.02e23
F = 9.65e4
rows = []


def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-300):
        mark = '≠'
    else:
        s = f'{book:.6g}'
        mant = s.split('e')[0]
        dec = len(mant.split('.')[1]) if '.' in mant else 0
        e = int(s.split('e')[1]) if 'e' in s else 0
        r = round(ours / 10**e, dec) * 10**e
        mark = ' ' if abs(r - book) <= 1e-9 * max(abs(book), 1e-300) else '≈'
    rows.append((no, what, ours, book, mark))


chk('20.1', '⟨v⟩, мм/с', 0.8 / (E * 2.5e28 * 4e-6) * 1e3, 0.05)
n = 2 * 8.93e3 * NA / 0.064
chk('20.2', '⟨v⟩, мкм/с (в книге 3,7)', 10 / (E * n * 1e-6) * 1e6, 3.7, 0.02)
n = 2.70e3 * NA / 0.027
chk('20.3', '⟨v⟩, мм/с', 1e6 / (E * n) * 1e3, 0.1, 0.05)
chk('20.4', 'E, В/м', 17e-9 * 3e6, 0.05, 0.03)
R = 17e-9 * 2 / 0.4e-6
chk('20.5', 'N, 10¹⁹ с⁻¹', sqrt(0.35 / R) / E / 1e19, 1.27)
chk('20.6', 'E, В/м', sqrt(216 / (6e-6 * 60) * 17e-9), 0.1, 0.02)
chk('20.7', 'E, пВ/м', ME * 100 / E * 1e12, 568)
chk('20.8', 'U, мкВ', ME * 1e4**2 * 0.5**2 / (2 * E) * 1e6, 71, 0.01)
chk('20.9', 'Q, мкКл', ME * 10 * 200 / (E * 10e-3) * 1e6, 1.14)
chk('20.10', '⟨l⟩, нм', 2 * ME * 1e6 * 1e7 / (E**2 * 1e28) * 1e9, 71, 0.01)
chk('20.11', 'z, 10¹⁴', E**2 * 1e29 / (2 * ME * 1e7) / 1e14, 1.4, 0.01)
T = 6.7e-6 * E**2 / (3 * KB**2)
chk('20.12', '⟨ε⟩, мэВ', 1.5 * KB * T / E * 1e3, 39, 0.01)
chk('20.13', 'w, кВт/м³', 10e6 * 1e-3 / 1e3, 10)
chk('20.14', 't, °C', 37e-6 * 105 / 43e-6, 90, 0.01)
chk('20.15', 'k, 10⁻⁵ В/К', 26e-6 * 84 / 50 / 1e-5, 4.4, 0.01)
chk('20.16', 'A_r', 1.02e-3 * F * 2 / (5 * 600) * 1e3, 65.4)
chk('20.17', 'Z железа', 2 * 56 * 3.9 / (65.4 * 2.24), 3, 0.01)
I = (4 - 1.5) / 0.6
chk('20.18', 'm, г', 0.064 * I * 600 / (F * 2) * 1e3, 0.83)
chk('20.19', 'h, мкм', 0.064 * 80 * 5 * 3600 / (F * 2 * 8.93e3) * 1e6, 54, 0.01)
chk('20.20', 'm, мг', 0.064 * 0.5 * 2 * 20 / (F * 2) * 1e6, 6.6)
chk('20.21', 'Z', 193e3 / F, 2)
nu = 2 * 300 / (F * 2)
chk('20.22', 'ν, ммоль', nu * 1e3, 3.12)
chk('20.22', 'N, 10²¹', nu * NA / 1e21, 1.87)
chk('20.23', 'N, 10¹⁷', 10 * 300 * 1e-4 / (2 * E) / 1e17, 9.3)
chk('20.24', 'U_i, В', 2.18e-18 / E, 13.6)
chk('20.25', 'v_min, 10⁶ м/с', sqrt(2 * E * 14.5 / ME) / 1e6, 2.3, 0.02)
chk('20.26', 'T при (3/2)kT = eU, кК', 2 * E * 13.6 / (3 * KB) / 1e3, 210)
chk('20.26', 'T при (3/2)kT = 2eU, кК', 4 * E * 13.6 / (3 * KB) / 1e3, 210)
chk('20.27', 't, мс', 0.02 / (2e-4 * 5e3 / 0.04) * 1e3, 0.8)
chk('20.28', 'γ, нСм/м', E * 1e13 * (1.27e-4 + 1.81e-4) * 1e9, 0.5, 0.02)
chk('20.29', 'n, 10¹⁴ м⁻³', 1.2e-6 / (0.03 * E * (1.4e-4 + 1.9e-4) * 100 / 0.02) / 1e14, 1.52)
chk('20.30', 'n₀, 10⁷ (см³·с)⁻¹', 4e-9 / (E * 0.5e-3) / 1e6 / 1e7, 5)
chk('20.31', 'I_нас, нА', E * 1e14 * 0.01 * 0.01 * 1e9, 1.6)
chk('20.32', 'n, 10⁹ (см³·с)⁻¹', 16e-6 / (E * 0.05) / 1e6 / 1e9, 2)

for no, what, ours, book, mark in rows:
    print(f'{mark} {no:6} {what:36} наш {ours:12.5g}   книга {book:g}')
print(f'\nрасхождений ≠: {sum(r[4] == "≠" for r in rows)}  в последней цифре ≈: {sum(r[4] == "≈" for r in rows)}  всего строк: {len(rows)}')
