"""Проверка ответов § 5 «Релятивистская механика» (задачи 5.1–5.44).

Каждая строка: номер, величина, наш расчёт, ответ книги. Пометки:
  «≠» — расхождение больше допуска (0,5 %): ошибка в книге или у нас, разбирать;
  «≈» — наш ответ, округлённый как в книге, отличается в последней цифре.
Постоянные — табл. 8, 22, 24: c = 3,00·10⁸ м/с, e = 1,60·10⁻¹⁹ Кл; электрон m₀ = 9,11·10⁻³¹ кг, E₀ = 0,511 МэВ;
протон 1,67·10⁻²⁷ кг, 938 МэВ; α-частица 6,64·10⁻²⁷ кг; e/m₀ = 1,76·10¹¹ Кл/кг; Земля–Солнце 1,49·10¹¹ м.
Удельная теплоёмкость воды 4,19 кДж/(кг·К). Год = 365 сут.
Запуск:  python -X utf8 tools/check_relyativ.py
"""
from math import sqrt, pi, atan, degrees, radians, tan, cos

c, eV = 3e8, 1.6e-19
ME, EE, MP, EP, MA = 9.11e-31, 0.511, 1.67e-27, 938, 6.64e-27
YEAR = 365 * 86400
rows = []


def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-300):
        mark = '≠'
    else:
        s = f'{book:.6g}'
        mant = s.split('e')[0]
        dec = len(mant.split('.')[1]) if '.' in mant else 0
        exp = int(s.split('e')[1]) if 'e' in s else 0
        r = round(ours / 10**exp, dec) * 10**exp
        mark = ' ' if abs(r - book) <= 1e-9 * max(abs(book), 1e-300) else '≈'
    rows.append((no, what, ours, book, mark))


gam = lambda b: 1 / sqrt(1 - b * b)
beta_T = lambda T, E0: sqrt((2 * E0 + T) * T) / (E0 + T)
add = lambda u, v: (u + v) / (1 + u * v)                      # в долях c

# --- длины и интервалы времени ---
chk('5.1', 'u, км/с', c * sqrt(2 * 0.1e-6 / 1) / 1e3, 134)
chk('5.2', 'u, км/с', c * sqrt(2 * 10e-12 / 1) / 1e3, 1.34)
chk('5.3', 'отставание, с', (7.9e3 / c)**2 / 2 * 0.5 * YEAR, 0.57)
chk('5.4', 'γ', gam(0.6), 1.25)
dx, dy = cos(radians(45)) * sqrt(1 - 0.64), cos(radians(45))
chk('5.5', 'l, м', sqrt(dx**2 + dy**2), 0.825)
chk('5.5', 'φ, °', degrees(atan(dy / dx)), 59)
chk('5.5', 'φ по формуле книги (без корня)', degrees(atan(1 / (1 - 0.64))), 59)
a6 = degrees(atan(gam(0.95)))
chk('5.6', 'угол диагонали с осью x, °', a6, 72.66)
print(f'5.6: диагонали пересекаются под углами {2 * a6:.1f}° и {180 - 2 * a6:.1f}°')
chk('5.7', 'τ0, нс', 75 / (0.995 * c) * sqrt(1 - 0.995**2) * 1e9, 25)
chk('5.8', 'β', 1 / sqrt(1 + (2e-6 * c / 6e3)**2), 0.995)

# --- сложение скоростей ---
chk('5.10', '1) u21/c', (0.9 - 0.6) / (1 - 0.9 * 0.6), 0.195)
chk('5.10', '1) по книге (+ в знаменателе)', (0.9 - 0.6) / (1 + 0.9 * 0.6), 0.195)
chk('5.10', '2) u21/c', add(0.9, 0.6), 0.974)
chk('5.11', 'v/c (u — скорость одной относительно другой)', 2 - sqrt(3), 0.268)
chk('5.13', 'u21/c', (0.75 - 0.4) / (1 - 0.75 * 0.4), 0.5)
chk('5.14', 'u21/c', add(0.9, 0.9), 0.994)

# --- масса и импульс ---
chk('5.15', 'm/m0', gam(0.5), 1.15)
chk('5.16', 'β', sqrt(1 - 1 / 9), 0.943)
chk('5.17', 'm/m0', 1.76e11 / 0.88e11, 2)
chk('5.17', 'β', sqrt(1 - 1 / 4), 0.866)
chk('5.18', '%', (gam(3e7 / c) - 1) * 100, 0.5)
chk('5.20', 'p', ME * c * 0.6 * gam(0.6), 2.05e-22)
chk('5.21', 'β', 1 / sqrt(2), 0.707)
chk('5.22', '1) m/m0', gam(0.8), 1.67)
V22 = gam(0.8) * 0.8 / (gam(0.8) + 1)
chk('5.22', '2) V/c', V22, 0.5)
chk('5.22', '3) m/m0', gam(V22), 1.15)
chk('5.23', 'VC/c', gam(0.6) * 0.6 / (gam(0.6) + 2), 0.231)

# --- масса и энергия ---
chk('5.24', 'Δm, кг', 1 / c**2, 11.1e-18)
chk('5.25', 'ΔE, Дж', 1e-3 * c**2, 90e12)
for name, m, bJ, bM in (('электрон', ME, 81.6e-15, 0.511), ('протон', MP, 150e-12, 938), ('α', MA, 596e-12, 3.73e3)):
    chk('5.26', f'{name}, Дж', m * c**2, bJ)
    chk('5.26', f'{name}, МэВ', m * c**2 / eV / 1e6, bM)
chk('5.27', 'Δm, кг', 4.19e3 * 1.03e3 * 1.37e18 * 1 / c**2, 6.57e7)
P = 1.4e3 * 4 * pi * 1.49e11**2
chk('5.28', '1) Δm Солнца, кг', P * YEAR / c**2, 1.37e17)
chk('5.28', '2) Δm океана, кг', 0.5 * 1.4e3 * 3.6e14 * YEAR / c**2, 8.82e7)

# --- кинетическая энергия ---
chk('5.29', 'электрон m/m0', 1 + 10 / EE, 20.6)
chk('5.29', 'протон m/m0', 1 + 10 / EP, 1.01)
chk('5.30', 'mp/me', (EP + 1e3) / (EE + 1e3), 1.94)
chk('5.31', 'T, МэВ', EE * (gam(0.8) - 1), 0.341)
chk('5.32', 'v, м/с', c * sqrt(3) / 2, 2.6e8)
chk('5.33', '1) v, Мм/с', beta_T(4, EE) * c / 1e6, 298)
chk('5.33', '2) v, Мм/с', beta_T(1e-3, EE) * c / 1e6, 18.9)
chk('5.34', '1) v, Мм/с', beta_T(1, EP) * c / 1e6, 13.8)
chk('5.34', '2) v, Мм/с', beta_T(2e3, EP) * c / 1e6, 263)
for no, b, bk in ((1, 0.2, 0.03), (2, 0.8, 0.52)):
    Tr = gam(b) - 1
    chk('5.36', f'{no}) ошибка', (Tr - b * b / 2) / Tr, bk)
u37 = add(sqrt(3) / 2, sqrt(3) / 2)
chk('5.37', '1) β', sqrt(3) / 2, 0.866)
chk('5.37', '2) u/c', u37, 0.9897)
chk('5.37', '3) T/m0c²', gam(u37) - 1, 6)

# --- энергия и импульс ---
chk('5.39', 'p/m0c', sqrt(3), 1.73)
chk('5.40', 'T/m0c²', sqrt(2) - 1, 0.414)
chk('5.41', 'p2/p1', sqrt(4 * 6) / sqrt(3), 2.82)
chk('5.42', '1) T2/T1', (sqrt(5) - 1) / (sqrt(2) - 1), 2.98)
chk('5.42', '2) E2/E1', sqrt(5) / sqrt(2), 1.58)
E1 = sqrt(2)                                                   # полная энергия налетающей, в m0c²
chk('5.43', '1) β', 1 / sqrt(2), 0.707)
chk('5.43', '2) m′/m0', E1 + 1, 2.4142)
chk('5.43', '3) β′', 1 / (E1 + 1), 0.414)
chk('5.43', '4) m0′/m0', sqrt((E1 + 1)**2 - 1), 2.1973)
chk('5.43', '5) T до', E1 - 1, 0.414)
chk('5.43', '5) T′', E1 + 1 - sqrt((E1 + 1)**2 - 1), 0.217)
Etot, pc = 3, sqrt(3)                                          # T = m0c²: E = 2, плюс покоящаяся 1
chk('5.44', "T' в Ц-системе, m0c²", sqrt(Etot**2 - pc**2) - 2, 0.551)
chk('5.44', 'по книге: 3 − √6 (энергия движения ц. масс)', 3 - sqrt(6), 0.551)

for no, what, ours, book, mark in rows:
    print(f'{mark} {no:5} {what:34} наш {ours:12.5g}   книга {book:.4g}')
print('\nрасхождений ≠:', sum(r[4] == '≠' for r in rows), ' в последней цифре ≈:', sum(r[4] == '≈' for r in rows), ' всего строк:', len(rows))
