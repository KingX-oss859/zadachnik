"""Проверка ответов § 27 «Магнитные свойства вещества» (27.1–27.24).

Пометки: «≠» — расхождение больше допуска (0,5 %); «≈» — отличие в последней цифре.
μB = 9,27·10⁻²⁴ Дж/Тл; k = 1,38·10⁻²³ Дж/К; N_A = 6,02·10²³ моль⁻¹; r1 = 52,9 пм;
n0 = 2,69·10²⁵ м⁻³ (н. у.); плотности — табл. 9; молярные массы: Mn 55, Pt 195, Al 27, Cu 63,5,
AgBr 188, Cr₂O₃ 152, V₂O₃ 150, Fe 56 г/моль. Кривая стали — оцифровка рис. 24.1.
Запуск:  python -X utf8 tools/check_magnitnye_svoystva.py
"""
from math import pi, sqrt, sin, cos, radians

MU0 = 4 * pi * 1e-7
E = 1.60e-19
ME = 9.11e-31
K = 8.99e9
rows = []


def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-300):
        mark = '≠'
    else:
        s = f'{book:.6g}'
        mant = s.split('e')[0]
        dec = len(mant.split('.')[1]) if '.' in mant else 0
        e = int(s.split('e')[1]) if 'e' in s else 0
        r = round(ours / 10**e, dec) * 10**e
        mark = ' ' if abs(r - book) <= 1e-9 * max(abs(book), 1e-300) else '≈'
    rows.append((no, what, ours, book, mark))


from math import exp, tanh, log
MB, KB, NA, R1, N0 = 9.27e-24, 1.38e-23, 6.02e23, 52.9e-12, 2.69e25


def lang(a):
    return 1 / tanh(a) - 1 / a


chk('27.1', 'J, кА/м', 6e28 * MB / 1e3, 556)
J = 1.21e-4 * 1e5
chk('27.2', 'J, А/м', J, 12.1)
chk('27.2', 'J_уд, мА·м²/кг (ρ = 7,40)', J / 7.40e3 * 1e3, 1.66)
chk('27.2', 'J_m, мкА·м²/моль', J / 7.40e3 * 0.055 * 1e6, 91)
chk('27.3', 'χ, 10⁻⁵ (в книге −7,3)', -7.5e-10 * 6.47e3 / 0.188 / 1e-5, -7.3)
chk('27.4', 'χ, 10⁻⁵ (в книге 1)', 1.30e-9 * 21.4e3 / 1e-5, 1)
chk('27.4', 'χ_m, 10⁻¹⁰ м³/моль (в книге 1)', 1.30e-9 * 0.195 / 1e-10, 1)
chk('27.5', 'χ_уд, 10⁻⁹ м³/кг', 2.1e-5 / 2.70e3 / 1e-9, 7.8)
chk('27.5', 'χ_m, 10⁻¹⁰ м³/моль', 2.1e-5 / 2.70e3 * 0.027 / 1e-10, 2.1)
chk('27.6', '|p_m|, мкА·м²', 4 / 3 * pi * 1.5e-4 * 0.5 / MU0 * 0.01**3 * 1e6, 250)
J = -1.1e-9 * 8.93e3 * 1e6
chk('27.7', 'J, А/м', J, -9.8)
chk('27.7', 'B, Тл', MU0 * (1e6 + J), 1.26)
chk('27.8', 'ω_L, 10⁶ с⁻¹', E * 50e-6 / (2 * ME) / 1e6, 4.4)
r2 = 2 / 3 * R1**2
chk('27.9', 'M, 10⁻²⁹ (e²B⟨r²⟩/4m, как в книге)', E**2 * 1 * r2 / (4 * ME) / 1e-29, 1.31)
chk('27.9', 'M, 10⁻²⁹ (e²B⟨r²⟩/6m — общая формула)', E**2 * 1 * r2 / (6 * ME) / 1e-29, 1.31)
chk('27.10', 'M_J, μB', sqrt(3 * KB * 300 * 5.8e-8 / (MU0 * NA)) / MB, 3.34)
chk('27.11', 'M_J, μB', sqrt(3 * KB * 290 * 1.89e-7 * 0.150 / (MU0 * NA)) / MB, 2.24)
M = 2.8 * MB
chk('27.12', 'J (слабое поле), мА/м', N0 * M**2 * 0.01 / (3 * KB * 273) * 1e3, 15.9)
chk('27.12', 'J (насыщение), А/м', N0 * M, 695)
lo, hi = 0.01, 3
for _ in range(100):
    mid = (lo + hi) / 2
    if (mid / 3 - lang(mid)) / lang(mid) < 0.01:
        lo = mid
    else:
        hi = mid
a1 = lo
chk('27.14', 'a_max (точно)', a1, 0.387)
chk('27.13', 'B_max, Тл (в книге 54)', a1 * KB * 300 / MB, 54)
chk('27.15', 'T, К (классическое распределение)', MB * 8 / (KB * -log(1e-3 / (1 + 1e-3))), 0.78)
chk('27.16', '1) N+/N−', exp(MB * 1 / (KB * 300)), 1.0022)
chk('27.16', '2) N+/N− (в книге 1,91)', exp(MB * 1 / (KB * 1)), 1.91)
chk('27.17', 'B2, Тл', 0.5 * 450 / 300, 0.75)
# сталь по рис. 24.1 при H = 1600 А/м: B ≈ 1,23 Тл
chk('27.18', 'J, кА/м (B = 1,23 Тл)', (1.23 / MU0 - 1600) / 1e3, 991, 0.03)
chk('27.19', 'μ', 1 + 0.8 / 10e-6 / 800, 101)
n = 7.87e3 * NA / 0.056
chk('27.20', '⟨n⟩, μB', 1.84e6 / (n * MB), 2.36)
chk('27.21', 'J_нас, МА/м', 4 * MB * n / 1e6, 3.13)
chk('27.22', '1) Δν, 10⁹ с⁻¹', E * 0.2 / (4 * pi * ME) / 1e9, 2.80)
chk('27.22', '2) I, 10⁻¹⁰ А', E**2 * 0.2 / (4 * pi * ME) / 1e-10, 4.48)
chk('27.22', '3) M, 10⁻²⁹ А·м² (в книге 10⁻¹⁹)', E**2 * 0.2 * 1e-20 / (4 * ME) / 1e-29, 1.41)
chk('27.23', '|J_m|, мкА·м²/моль (в книге 4)', E**2 * NA / (3 * ME) * 3.4e-21 * 0.5 * 1e6, 4)
f = lambda chi, Z: sqrt(6 * ME * chi / (MU0 * E**2 * NA * Z))
chk('27.24', '1) ⟨ρ⟩ Ne, 10⁻¹¹ м', f(9.05e-11, 8) / 1e-11, 5.6)
chk('27.24', '2) ⟨ρ⟩ Ar при χ = 2,44·10⁻¹¹', f(2.44e-11, 8) / 1e-11, 9.3)
chk('27.24', '2) ⟨ρ⟩ Ar при χ = 2,44·10⁻¹⁰', f(2.44e-10, 8) / 1e-11, 9.3)

for no, what, ours, book, mark in rows:
    print(f'{mark} {no:6} {what:44} наш {ours:12.5g}   книга {book:g}')
print(f'\nрасхождений ≠: {sum(r[4] == "≠" for r in rows)}  в последней цифре ≈: {sum(r[4] == "≈" for r in rows)}  всего строк: {len(rows)}')
