"""Проверка ответов § 13 «Закон Кулона. Взаимодействие заряженных тел» (задачи 13.1–13.22).

Каждая строка: номер, величина, наш расчёт, ответ книги. Пометки:
  «≠» — расхождение больше допуска (0,5 %): ошибка в книге или у нас, разбирать;
  «≈» — наш ответ, округлённый как в книге, отличается в последней цифре.
Постоянные — табл. 24: ε0 = 8,85·10⁻¹² Ф/м, e = 1,60·10⁻¹⁹ Кл, m_e = 9,11·10⁻³¹ кг, G = 6,67·10⁻¹¹, g = 9,81.
Силы от заряженных нитей проверяются численным интегрированием закона Кулона.
Запуск:  python -X utf8 tools/check_kulon.py
"""
from math import sqrt, pi, sin, cos, tan, radians

EPS0, E, ME, G, g = 8.85e-12, 1.60e-19, 9.11e-31, 6.67e-11, 9.81
K = 1 / (4 * pi * EPS0)
rows = []


def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-300):
        mark = '≠'
    else:
        s = f'{book:.6g}'
        mant = s.split('e')[0]
        dec = len(mant.split('.')[1]) if '.' in mant else 0
        e = int(s.split('e')[1]) if 'e' in s else 0
        r = round(ours / 10**e, dec) * 10**e
        mark = ' ' if abs(r - book) <= 1e-9 * max(abs(book), 1e-300) else '≈'
    rows.append((no, what, ours, book, mark))


def line_force(q, tau, pts, n=200000):
    """Сила на заряд q в начале координат от нити, заданной функцией t → (x, y), t ∈ [0; 1], и её длиной."""
    f, L = pts
    Fx = Fy = 0.0
    for i in range(n):
        t = (i + 0.5) / n
        x, y = f(t)
        r3 = (x * x + y * y)**1.5
        dq = tau * L / n
        Fx -= K * q * dq * x / r3
        Fy -= K * q * dq * y / r3
    return Fx, Fy


chk('13.1', 'F, Н', K * 1 * 1 / 1, 9e9, 0.01)
r = 2 * 0.2 * sin(radians(30))
chk('13.2', 'Q, нКл', r * sqrt(1e-4 * g * tan(radians(30)) / K) * 1e9, 50.1)
chk('13.3', 'ε', 1.6e3 / (1.6e3 - 0.8e3), 2)
chk('13.4', 'Q, 10⁻¹⁵ Кл', 1e-3 * sqrt(G / K) * 1e15, 86.7)
v = E / sqrt(4 * pi * EPS0 * ME * 53e-12)
chk('13.5', 'v, 10⁶ м/с', v / 1e6, 2.19)
chk('13.5', 'n, 10¹⁵ с⁻¹', v / (2 * pi * 53e-12) / 1e15, 6.58)
chk('13.6', 'F, мН', K * 1e-6 * 1e-7 * sqrt(1 / 0.06**4 + 1 / 0.08**4) * 1e3, 287)
F = [0.0, 0.0]
for i in range(6):                                       # шестиугольник: заряды (i+1)Q в вершинах
    ang = radians(60 * i)
    F[0] -= K * (i + 1) * 1e-7 * 1e-7 / 0.01 * cos(ang)
    F[1] -= K * (i + 1) * 1e-7 * 1e-7 / 0.01 * sin(ang)
chk('13.7', 'F, мН', sqrt(F[0]**2 + F[1]**2) * 1e3, 54)


def pair(r, F1, F2, sign):
    S = 2 * r * sqrt(F2 / K)
    P = sign * F1 * r * r / K
    d = sqrt(S * S - 4 * P)
    return (S + d) / 2, (S - d) / 2


q1, q2 = pair(0.6, 70e-6, 1.6e-4, 1)
chk('13.8', 'Q1, мкКл', q1 * 1e6, 0.14, 0.01)
chk('13.8', 'Q2, нКл', q2 * 1e9, 20, 0.01)
q1, q2 = pair(0.3, 90e-6, 160e-6, -1)
chk('13.9', 'Q1, мкКл', q1 * 1e6, 0.09, 0.01)
chk('13.9', 'Q2, мкКл', q2 * 1e6, -0.01, 0.01)
chk('13.10', 'x от 4Q, см', 60 * 2 / 3, 40)
chk('13.11', 'Q3, нКл', -720 * (20 / 60)**2, -80)
chk('13.12', 'Q1/Q', -1 / sqrt(3), -0.577)
chk('13.13', 'Q1, нКл', -(sqrt(2) + 0.5) / 2 * 0.3, -0.287)
Fx, _ = line_force(100e-9, 1e-6, (lambda t: (-0.2 - 0.1 * t, 0), 0.1))
chk('13.14', 'F, мН', Fx * 1e3, 1.5, 0.01)
chk('13.15', 'F, мН', K * 10e-9 * 1e-5 / 0.2 * 1e3, 4.5, 0.01)
Fx, Fy = line_force(10e-9, 1e-5, (lambda t: (0, -0.2 - 2000 * t**2), 2000))   # проверка формулы √2 Qτ/(4πε0 a)
chk('13.16', 'F, мН', sqrt(2) * K * 10e-9 * 1e-5 / 0.2 * 1e3, 6.37)
Fx, Fy = line_force(1e-9, 10e-9, (lambda t: (-0.1 + 0.2 * t, -0.1), 0.2))
chk('13.17', 'F, мкН (интеграл)', sqrt(Fx * Fx + Fy * Fy) * 1e6, 1.27)
chk('13.18', 'F, мН', 2 * K * 10e-9 * 1e-5 / 0.2 * 1e3, 9, 0.01)
chk('13.19', 'F, мН', sqrt(5) * K * 0.1e-6 * 1e-6 / 0.5 * 1e3, 4.03)
chk('13.20', '1) F, мкН (в книге «15,7 кН»)', K * 1e-7 * 1e-8 * 0.2 / (0.1**2 + 0.2**2)**1.5 * 1e6, 15.7)
chk('13.20', '2) F, мкН', K * 1e-7 * 1e-8 / 2**2 * 1e6, 2.25)
chk('13.21', 'F, мН', 2 * K * 20e-9 * 1e-6 / 0.1 * 1e3, 3.6, 0.01)
chk('13.22', 'F, мкН', K * 400e-9 * 1e-9 / 0.1 * 1e6, 35)

for no, what, ours, book, mark in rows:
    print(f'{mark} {no:6} {what:32} наш {ours:12.5g}   книга {book:.4g}')
print('\nрасхождений ≠:', sum(r[4] == '≠' for r in rows), ' в последней цифре ≈:', sum(r[4] == '≈' for r in rows), ' всего строк:', len(rows))
