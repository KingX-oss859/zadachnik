"""Проверка ответов § 7 «Волны в упругой среде. Акустика» (задачи 7.1–7.40).

Каждая строка: номер, величина, наш расчёт, ответ книги. Пометки:
  «≠» — расхождение больше допуска (0,5 %): ошибка в книге или у нас, разбирать;
  «≈» — наш ответ, округлённый как в книге, отличается в последней цифре.
Постоянные — табл. 9, 11, 16, 24: R = 8,31 Дж/(моль·К); скорость звука в воздухе (н. у.) 332 м/с — табл. 16
(сноска 15 книги: если скорость не дана и её не из чего вычислить); воздух γ = 1,4, M = 0,029 кг/моль;
модули Юнга и плотности металлов — табл. 11 и 9; нормальное давление 101,3 кПа.
Запуск:  python -X utf8 tools/check_volny.py
"""
from math import sqrt, pi, cos, sin

R, C_AIR = 8.31, 332
rows = []


def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-300):
        mark = '≠'
    else:
        s = f'{book:.6g}'
        mant = s.split('e')[0]
        dec = len(mant.split('.')[1]) if '.' in mant else 0
        exp = int(s.split('e')[1]) if 'e' in s else 0
        r = round(ours / 10**exp, dec) * 10**exp
        mark = ' ' if abs(r - book) <= 1e-9 * max(abs(book), 1e-300) else '≈'
    rows.append((no, what, ours, book, mark))


c_gas = lambda T, M=0.029, g=1.4: sqrt(g * R * T / M)

# --- уравнение плоской волны ---
A, w, k = 0.005, 628, 2
chk('7.1', 'ν, Гц', w / (2 * pi), 100)
chk('7.1', 'λ, м', 2 * pi / k, 3.14)
chk('7.1', 'c, м/с', w / k, 314)
chk('7.1', 'vmax', A * w, 3.14)
chk('7.1', 'amax', A * w**2, 1.97e3)
chk('7.3', 'ξ, м', 4e-3 * cos(2 * pi * 200 * (0.1 - 1 / 300)), -2e-6)
chk('7.4', 'c', 0.7 * 500, 350)
chk('7.4', 'vmax', 0.25e-3 * 2 * pi * 500, 0.79)
T5, A5, l5 = 3e-3, 0.2e-3, 1.2
ph5 = 2 * pi * (7e-3 / T5 - 2 / l5)
w5 = 2 * pi / T5
chk('7.5', 'ξ, м', A5 * cos(ph5), -0.1e-3)
chk('7.5', 'v', -A5 * w5 * sin(ph5), 0.363)
chk('7.5', 'a', -A5 * w5**2 * cos(ph5), 439)
chk('7.6', 'ξ, см', 10 * cos(2 * pi * (0.9 - 0.75)), 5.88)
ph7 = 2 * pi / 1.2 * (4 - 45 / 15)
chk('7.7', 'ξ, см (синус: старт из равновесия)', 2 * sin(ph7), -1.73)
chk('7.7', 'ξ, см (косинус, как в примере 1)', 2 * cos(ph7), -1.73)
chk('7.8', 'Δφ', 2 * pi * 0.5 / (50 * 0.05), 1.26)
chk('7.9', 'Δφ', 2 * pi * 2 * 5 / 40, 1.57)
chk('7.10', 'ν', 100 / 2, 50)
chk('7.11', 'c', 2 * pi * 0.1 * 25 / (pi / 3), 15)

# --- скорость звука ---
chk('7.12', 'Al, м/с', sqrt(69e9 / 2700), 5.05e3)
chk('7.12', 'Cu', sqrt(98e9 / 8930), 3.31e3)
chk('7.12', 'W', sqrt(380e9 / 19300), 4.44e3)
chk('7.13', 'λmax, м', 340 / 16, 21)
chk('7.13', 'λmin, м', 340 / 20e3, 17e-3)
chk('7.14', 'c N2', c_gas(300, 0.028), 350)
chk('7.15', 'c 290 К', c_gas(290), 339)
chk('7.15', 'c 350 К', c_gas(350), 375)
ta = 800 / c_gas(350)
chk('7.16', 'c воды', 800 / (ta - 1.78), 1.45e3)
chk('7.16', 'если c возд = 343', 800 / (800 / 343 - 1.78), 1.45e3)
chk('7.17', 'γ', 308**2 * 1.78 / 101.3e3, 1.67)
chk('7.18', 'c(H2)/c(CO2)', sqrt(1.4 / 0.002 / (4 / 3 / 0.044)), 4.8)
a19 = 7e-3
chk('7.19', 't, с', sqrt(0.029 / (1.4 * R)) * 2 / a19 * (sqrt(300) - sqrt(300 - a19 * 8e3)), 24.3)

# --- суперпозиция ---
chk('7.20', 'A, мм', 2 * abs(cos(pi * (5.4 - 3.5) / 0.6)), 1.73)
lam21 = 340 / 3.4e3
chk('7.21', 'λ/4, см', lam21 / 4 * 100, 2.5)
chk('7.22', '1) λ, см', 15 / 3, 5)
chk('7.22', '2) λ, см', 15 / 1.5, 10)
c23 = c_gas(300)
chk('7.23', '1) открытая', c23 / 2.4, 144)
chk('7.23', '2) закрытая', c23 / 4.8, 72)
chk('7.24', 'c', 4 * 0.195 * 440, 343)
chk('7.25', 'c', 2 * 0.375 * 440, 330)
chk('7.26', 'c латуни', 0.8 / 0.085 * C_AIR, 3.12e3)
chk('7.27', 'ν', sqrt(200e9 / 7870) / 2, 2.52e3)

# --- эффект Доплера (c = 332 м/с) ---
c = C_AIR
chk('7.28', '1) ν', 300 * c / (c - 10), 341)
chk('7.28', '2) ν', 300 * c / (c + 10), 268)
chk('7.28', 'книга: с u = 40 м/с, 1)', 300 * c / (c - 40), 341)
chk('7.29', 'приближается', 300 * (c + 40) / c, 366)
chk('7.29', 'удаляется', 300 * (c - 40) / c, 264)
u30 = c * (1100 - 900) / (1100 + 900)
chk('7.30', 'u, км/ч', u30 * 3.6, 120)
chk('7.30', 'ν0', 1100 * (c - u30) / c, 990)
chk('7.31', 'Δν/ν', 2 * 15 * c / (c**2 - 15**2), 0.09)
chk('7.32', 'u, м/с (от резонатора)', 8e3 * 0.042 - c, 4.1)
chk('7.32', 'если c = 340: к резонатору', 340 - 8e3 * 0.042, 4.1)
chk('7.33', '1) τ', 5 * (348 - 120 / 3.6) / 348, 4.5)
chk('7.33', '2) τ', 5 * (348 + 120 / 3.6) / 348, 5.5)
chk('7.34', 'ν', 600 * (c + 20) / c, 636)
chk('7.35', '1) ν2', 600 * (c + 20) / (c - 30), 699)
chk('7.35', '2) ν2', 600 * (c - 20) / (c + 30), 517)
chk('7.35', 'сигналит вторая 1)', 600 * (c + 30) / (c - 20), 696)
chk('7.35', 'сигналит вторая 2)', 600 * (c - 30) / (c + 20), 515)
chk('7.36', 'u', 1500 * 250 / (2 * 50e3 + 250), 3.74)

# --- энергия ---
chk('7.37', 'W, Дж', 0.05 / c * pi * 0.1**2 * 5, 23.7e-6)
chk('7.38', 'w', 1 / c, 3.01e-3)
chk('7.39', 'w, Дж/м³', 10 / (4 * pi * 10**2) / c_gas(250), 0.251)
chk('7.40', 'N', 4 * pi * 25**2 * 0.02, 157)
chk('7.40', 'w', 0.02 / c, 60.2e-6)

for no, what, ours, book, mark in rows:
    print(f'{mark} {no:5} {what:36} наш {ours:12.5g}   книга {book:.4g}')
print('\nрасхождений ≠:', sum(r[4] == '≠' for r in rows), ' в последней цифре ≈:', sum(r[4] == '≈' for r in rows), ' всего строк:', len(rows))
