def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-300):
        mark = '≠'
    else:
        s = f'{book:.6g}'
        mant = s.split('e')[0]
        dec = len(mant.split('.')[1]) if '.' in mant else 0
        e = int(s.split('e')[1]) if 'e' in s else 0
        r = round(ours / 10**e, dec) * 10**e
        mark = ' ' if abs(r - book) <= 1e-9 * max(abs(book), 1e-300) else '≈'
    rows.append((no, what, ours, book, mark))


def bz_seg(p, q, I, n=4000):
    """Bz в начале координат от прямого отрезка p→q в плоскости z = 0 (точно, формула отрезка)."""
    (x1, y1), (x2, y2) = p, q
    dx, dy = x2 - x1, y2 - y1
    L = sqrt(dx * dx + dy * dy)
    ux, uy = dx / L, dy / L
    cross = x1 * uy - y1 * ux          # (p − O) × u  → знак и расстояние
    d = abs(cross)
    if d < 1e-15:
        return 0.0
    t1 = -(x1 * ux + y1 * uy)          # проекции O на прямую относительно p
    a1, a2 = -t1, L - t1               # координаты концов вдоль прямой от основания перпендикуляра
    val = MU0 * I / (4 * pi * d) * (a2 / sqrt(a2 * a2 + d * d) - a1 / sqrt(a1 * a1 + d * d))
    return val * (1 if cross > 0 else -1)


def bz_arc(R, th1, th2, I):
    """Дуга радиуса R с центром в O от угла th1 до th2 (против часовой при th2 > th1)."""
    return MU0 * I * (th2 - th1) / (4 * pi * R)


def path(pts, I):
    return sum(bz_seg(pts[k], pts[k + 1], I) for k in range(len(pts) - 1))


