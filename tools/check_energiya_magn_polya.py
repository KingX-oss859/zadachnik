"""Проверка ответов § 26 «Энергия магнитного поля» (26.1–26.25).

Пометки: «≠» — расхождение больше допуска (0,5 %, для чтения графика — 5 %); «≈» — последняя цифра.
Кривые B(H) — оцифровка рис. 24.1 (та же таблица, что в check_zakon_polnogo_toka.py).
μ0 = 4π·10⁻⁷ Гн/м; ε0 = 8,85·10⁻¹² Ф/м; c = 3·10⁸ м/с.
Запуск:  python -X utf8 tools/check_energiya_magn_polya.py
"""
from math import pi, sqrt, sin, cos, radians

MU0 = 4 * pi * 1e-7
E = 1.60e-19
ME = 9.11e-31
K = 8.99e9
rows = []


def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-300):
        mark = '≠'
    else:
        s = f'{book:.6g}'
        mant = s.split('e')[0]
        dec = len(mant.split('.')[1]) if '.' in mant else 0
        e = int(s.split('e')[1]) if 'e' in s else 0
        r = round(ours / 10**e, dec) * 10**e
        mark = ' ' if abs(r - book) <= 1e-9 * max(abs(book), 1e-300) else '≈'
    rows.append((no, what, ours, book, mark))
CURVE = {
    'железо': [(200, .82), (250, .92), (300, .97), (500, 1.09), (700, 1.21), (1000, 1.29), (1500, 1.37), (1700, 1.39), (2000, 1.42), (2500, 1.44), (3000, 1.45)],
    'сталь': [(200, .45), (250, .55), (300, .64), (500, .88), (750, 1.0), (1000, 1.11), (1500, 1.22), (2000, 1.29), (2500, 1.32), (3000, 1.35)],
    'чугун': [(200, .10), (500, .23), (1000, .38), (1500, .49), (2000, .57), (2500, .61), (3000, .63)],
}


def B_of(mat, H):
    c = CURVE[mat]
    for (h1, b1), (h2, b2) in zip(c, c[1:]):
        if h1 <= H <= h2:
            return b1 + (b2 - b1) * (H - h1) / (h2 - h1)
    raise ValueError(H)


def H_of(mat, B):
    c = CURVE[mat]
    for (h1, b1), (h2, b2) in zip(c, c[1:]):
        if b1 <= B <= b2:
            return h1 + (h2 - h1) * (B - b1) / (b2 - b1)
    raise ValueError(B)


G = 0.05   # допуск для задач с графиком
EPS0, C = 8.85e-12, 3e8
chk('26.1', 'W, Дж', 0.2 * 10**2 / 2, 10)
chk('26.2', 'I, А', sqrt(2e-4 / 1e-4), 1.4, 0.02)
chk('26.3', 'W, мДж', 1000 * 0.1e-3 * 1 / 2 * 1e3, 50)
chk('26.4', 'W, Дж (в книге 0,15)', 200 * 0.5e-3 * 2.5 / 2, 0.15)
H = 0.6 / 0.4e-3
Bst = B_of('сталь', H)
chk('26.5', f'H = {H:.0f} А/м, B стали, Тл', Bst, 1.146, G)
chk('26.5', 'W, мДж', Bst * H / 2 * pi * 0.3 * 4e-4 * 1e3, 324, G)
chk('26.6', 'μ', 1 / (2 * MU0 * 200), 2000, 0.01)
chk('26.7', 'w, Дж/м³ (сталь, 0,5 Тл)', 0.5 * H_of('сталь', 0.5) / 2, 25, G)
chk('26.8', 'w2/w1', 1.0 * H_of('сталь', 1.0) / (0.5 * H_of('сталь', 0.5)), 6.4, G)
chk('26.9', 'w, Дж/м³', B_of('железо', 1200) * 1200 / 2, 800, G)
chk('26.10', 'w2/w1', B_of('сталь', 800) * 800 / (B_of('сталь', 200) * 200), 10.5, G)
H = sqrt(2 * 0.2 / MU0)
chk('26.11', f'H = {H:.0f} А/м, μ', B_of('железо', H) / (MU0 * H), 1600, G)
chk('26.12', 'w, кДж/м³', B_of('железо', 1600) * 1600 / 2 / 1e3, 1.1, G)
chk('26.13', 'w, Дж/м³', MU0 * (1000 * 16)**2 / 2, 161)
chk('26.14', 'I, А', sqrt(2 * 1 / MU0) / 1000, 1.26)
Cc = EPS0 * pi * 0.2**2 / 4 / 0.01
chk('26.15', 'T, нс (в книге 33,2)', 2 * pi * sqrt(1e-3 * Cc) * 1e9, 33.2)
L = MU0 * 1000**2 * 5e-4 / 0.4
chk('26.16', 'T, мкс', 2 * pi * sqrt(L * 500e-12) * 1e6, 5.57)
lam = 2 * pi * C * sqrt(20e-6 * 80e-9)
chk('26.17', 'λ, м', lam, 2380)
chk('26.17', 'Δλ, м (δC = 2 % → δλ = 1 %)', lam * 0.01, 23.8)
chk('26.18', 'I_max, А', 200 * sqrt(0.04e-6 / 1.6e-3), 1)
chk('26.19', 'U_max, В', 40e-3 * sqrt(0.5e-3 / 8e-12), 317)
L = MU0 * 1000**2 * 3e-4 / 0.5
Cc = EPS0 * 75e-4 / 5e-3
chk('26.20', 'T, нс', 2 * pi * sqrt(L * Cc) * 1e9, 628)
chk('26.21', 'ν, кГц', 1 / (2 * pi * sqrt(1e-6 * 1e-3)) / 1e3, 5.05)
chk('26.22', 'C, пФ', 300**2 / (4 * pi**2 * C**2 * 0.5e-3) * 1e12, 51)
chk('26.23', 'λ, м', 2 * pi * C * sqrt(4e-6 * 1.11e-9), 126)
chk('26.24', 'n', sqrt(2), 1.4, 0.02)
chk('26.25', 'ε', (C / (2 * 0.07 * 420e6))**2, 26, 0.01)

for no, what, ours, book, mark in rows:
    print(f'{mark} {no:6} {what:44} наш {ours:12.5g}   книга {book:g}')
print(f'\nрасхождений ≠: {sum(r[4] == "≠" for r in rows)}  в последней цифре ≈: {sum(r[4] == "≈" for r in rows)}  всего строк: {len(rows)}')
