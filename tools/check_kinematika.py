rows = []


def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-12):
        mark = '≠'
    else:
        dec = len(repr(float(book)).split('.')[1].rstrip('0')) if '.' in repr(float(book)) else 0
        r = round(ours, dec) if dec else round(ours)
        # «150» и т. п. — книга округлила до двух значащих цифр
        if not dec and abs(book) >= 100 and book % 10 == 0:
            r = round(ours, -1)
        mark = ' ' if abs(r - book) < 1e-9 else '≈'
    rows.append((no, what, ours, book, mark))


