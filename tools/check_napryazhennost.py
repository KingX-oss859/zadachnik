from math import sqrt, pi, sin, cos, asin, atan2, degrees, log, radians

EPS0 = 8.85e-12
K = 1 / (4 * pi * EPS0)
rows = []


def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-300):
        mark = '≠'
    else:
        s = f'{book:.6g}'
        mant = s.split('e')[0]
        dec = len(mant.split('.')[1]) if '.' in mant else 0
        e = int(s.split('e')[1]) if 'e' in s else 0
        r = round(ours / 10**e, dec) * 10**e
        mark = ' ' if abs(r - book) <= 1e-9 * max(abs(book), 1e-300) else '≈'
    rows.append((no, what, ours, book, mark))


def rod(tau, p0, p1, A, n=40000):
    """Поле в точке A от отрезка p0–p1 с линейной плотностью tau (численно)."""
    Ex = Ey = 0.0
    L = sqrt((p1[0] - p0[0])**2 + (p1[1] - p0[1])**2)
    for i in range(n):
        t = (i + 0.5) / n
        x, y = p0[0] + (p1[0] - p0[0]) * t, p0[1] + (p1[1] - p0[1]) * t
        dx, dy = A[0] - x, A[1] - y
        r3 = (dx * dx + dy * dy)**1.5
        Ex += K * tau * L / n * dx / r3
        Ey += K * tau * L / n * dy / r3
    return Ex, Ey


