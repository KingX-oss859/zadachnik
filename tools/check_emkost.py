"""Проверка ответов § 17 «Электрическая ёмкость. Конденсаторы» (задачи 17.1–17.25).

Пометки: «≠» — расхождение больше допуска (0,5 %); «≈» — отличие в последней цифре.
ε0 = 8,85·10⁻¹² Ф/м; ε — табл. 17: вода 81, слюда 7, стекло 7, парафин 2, фарфор 5, эбонит 3.
Схемы 17.20–17.25 — по рисункам; для мостовых схем (17.24, 17.25) ёмкость считается ещё и решением
системы уравнений для потенциалов узлов (проверка, что C₅ ни на что не влияет).
Запуск:  python -X utf8 tools/check_emkost.py
"""
from math import pi

EPS0 = 8.85e-12
rows = []


def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-300):
        mark = '≠'
    else:
        s = f'{book:.6g}'
        mant = s.split('e')[0]
        dec = len(mant.split('.')[1]) if '.' in mant else 0
        e = int(s.split('e')[1]) if 'e' in s else 0
        r = round(ours / 10**e, dec) * 10**e
        mark = ' ' if abs(r - book) <= 1e-9 * max(abs(book), 1e-300) else '≈'
    rows.append((no, what, ours, book, mark))


ser = lambda *c: 1 / sum(1 / x for x in c)


def bridge(C1, C2, C3, C4, C5):
    """Мост: вход — общий узел C1 и C3, выход — общий узел C2 и C4, C5 между узлами A (C1–C2) и B (C3–C4).
    Вход под потенциалом 1, выход 0; заряды в узлах A и B равны нулю."""
    # (φA − 1)C1 + φA C2 + (φA − φB)C5 = 0;  (φB − 1)C3 + φB C4 + (φB − φA)C5 = 0
    a11, a12, b1 = C1 + C2 + C5, -C5, C1
    a21, a22, b2 = -C5, C3 + C4 + C5, C3
    det = a11 * a22 - a12 * a21
    fa = (b1 * a22 - a12 * b2) / det
    fb = (a11 * b2 - a21 * b1) / det
    return C1 * (1 - fa) + C3 * (1 - fb)          # заряд, ушедший со входа, при U = 1


chk('17.1', 'C, пФ', 4 * pi * EPS0 * 0.01 * 1e12, 1.11)
chk('17.2', 'C, пФ', 4 * pi * EPS0 * 81 * 0.02 * 1e12, 180)
chk('17.3', 'C, мкФ', 4 * pi * EPS0 * 6.4e6 * 1e6, 712)
Q1, Q2 = 1e-9 * 2 / 8, 1e-9 * 6 / 8
