chk('17.7', 'Δφ₁, В', D / (EPS0 * 7) * 7e-3, 300)
chk('17.8', 'C, пФ (d = 1,33 мм; в книге 35,4)', EPS0 * 20e-4 / (0.7e-3 / 7 + 0.3e-3 / 3 + 0.33e-3) * 1e12, 35.4)
chk('17.8', 'C, пФ при d = 1,3 мм', EPS0 * 20e-4 / (0.7e-3 / 7 + 0.3e-3 / 3 + 0.3e-3) * 1e12, 35.4)
chk('17.9', 'ΔU, В', 0.2e-6 / EPS0 * 2e-3, 45.2)
chk('17.10', 'Δd, см', 1 - 1 / 2, 0.5)
chk('17.11', 'C, мкФ', 1.5 * 5 / (2 + 3 / 3), 2.5)
chk('17.12', 'U₂, В', 7 * 100, 700)
chk('17.13', 'C, пФ', 4 * pi * EPS0 * 2 * 0.02 * 0.021 / 0.001 * 1e12, 93.3)
C = 4 * pi * EPS0 * 2 * 0.1 * 0.102 / 0.002
chk('17.14', 'U, кВ', 5e-6 / C / 1e3, 4.41)
chk('17.15', 'ε', 600 / 100 - 1, 5)
