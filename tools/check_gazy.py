"""Проверка ответов § 8 «Молекулярное строение вещества. Законы идеальных газов» (задачи 8.1–8.45).

Каждая строка: номер, величина, наш расчёт, ответ книги. Пометки:
  «≠» — расхождение больше допуска (0,5 %): ошибка в книге или у нас, разбирать;
  «≈» — наш ответ, округлённый как в книге, отличается в последней цифре.
Постоянные — по табл. 24 приложения книги: N_A = 6,02·10²³, R = 8,31, V_m = 22,4·10⁻³ м³/моль, g = 9,81.
Нормальные условия: p0 = 101,3 кПа (760 мм рт. ст.), T0 = 273 К.
Плотности (табл. 9, 10): вода 1000, ртуть 13 600, сероуглерод 1260 кг/м³; воздух 1,29, водород 0,09 кг/м³.
Относительные атомные массы — по таблице Менделеева: H 1, He 4, C 12, N 14, O 16, F 19, Na 23, S 32, Cl 35,5, Hg 200,6, Po 210.
Запуск:  python -X utf8 tools/check_gazy.py
"""
from math import sqrt, pi

NA, R, VM, g = 6.02e23, 8.31, 22.4e-3, 9.81
P0, T0 = 101.3e3, 273
RHO_W, RHO_HG, RHO_CS2, RHO_AIR, RHO_H2 = 1000, 13600, 1260, 1.29, 0.09
k = 1e-3                          # кг/моль: M = Mr·k
rows = []


def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-300):
        mark = '≠'
    else:
        s = f'{book:.6g}'
        mant = s.split('e')[0]
        dec = len(mant.split('.')[1]) if '.' in mant else 0
        e = int(s.split('e')[1]) if 'e' in s else 0
        r = round(ours / 10**e, dec) * 10**e
        mark = ' ' if abs(r - book) <= 1e-9 * max(abs(book), 1e-300) else '≈'
    rows.append((no, what, ours, book, mark))


# --- молекулярное строение ---
chk('8.1', 'Mr воды', 2 * 1 + 16, 18)
chk('8.1', 'Mr CO2', 12 + 2 * 16, 44)
chk('8.1', 'Mr NaCl (22,99 + 35,45)', 22.99 + 35.45, 58.4)
chk('8.2', 'M H2SO4, г/моль', 2 + 32 + 64, 98)
chk('8.3', 'm1 CO2, кг', 44 * k / NA, 7.31e-26)
chk('8.3', 'm1 NaCl, кг', 58.44 * k / NA, 9.70e-26)
chk('8.4', 'ρ, кг/м³', 32 * k * 0.2 / 2e-3, 3.2)
chk('8.5', 'ν, моль', 0.2 / (28 * k), 7.14)
chk('8.5', 'N', 0.2 / (28 * k) * NA, 4.30e24)
chk('8.6', 'ν, моль', 4e-3 / (32 * k), 0.125)
chk('8.6', 'N (в книге 7,52·10²¹)', 4e-3 / (32 * k) * NA, 7.52e21)
chk('8.7', 'ν, моль', 11.2e-3 / VM, 0.5)
chk('8.7', 'm, г', 11.2e-3 / VM * 32, 16)
chk('8.8', 'ν, моль', 6.65e-3 * 3e-3 / (2 * k), 9.97e-3)
chk('8.9', 'N', NA * 0.5e-3 / VM, 1.34e22)
for name, A, bk in (('He', 4, 1.50e23), ('C', 12, 5.02e22), ('F', 19, 3.17e22), ('Po', 210, 2.87e21)):
    chk('8.10', 'N ' + name, 1e-3 / (A * k) * NA, bk)
chk('8.11', 'Mr', 1.12 * 5e-3 / (k * 0.2), 28)
chk('8.12', 'N (в книге 2,87·10²⁰)', 4 / 3 * 10e-3 / (28 * k) * NA, 2.87e20)
chk('8.13', 'd CS2, нм', (76 * k / (RHO_CS2 * NA))**(1 / 3) * 1e9, 0.464)
chk('8.13', 'd Hg, нм', (200.6 * k / (RHO_HG * NA))**(1 / 3) * 1e9, 0.290)
chk('8.14', '<l>/d', (VM / NA)**(1 / 3) / 0.311e-9, 10.7)
nu = 1.12e-3 / VM
chk('8.15', 'ν, ммоль', nu * 1e3, 50)
chk('8.15', 'ν мол, ммоль', nu * 0.7 * 1e3, 35)
chk('8.15', 'ν ат, ммоль', 2 * nu * 0.3 * 1e3, 30)
chk('8.15', 'ν полн, ммоль', nu * 1.3 * 1e3, 65)

# --- уравнение газового состояния ---
chk('8.16', 'F, кН', P0 * 1.6 / 0.1 * 200e-4 / 1e3, 32.3)
chk('8.17', 'p, кПа', 100 * (1 - 292 / 300), 2.67)
rgh = lambda h: RHO_HG * g * h
p_air = (P0 + rgh(0.10)) * 0.20 / (0.20 + (0.26 - 0.10) / 2)
chk('8.18', 'p, кПа', (p_air - rgh(0.26)) / 1e3, 47.2)
S = pi * 5**2 / 4                 # мм²
V2 = 10 + S * (100 - 10) / 2       # мм³
chk('8.19', 'p, кПа', ((P0 - rgh(0.10)) * 10 / V2 + rgh(0.01)) / 1e3, 2.32)
chk('8.20', 't2, °C', 2 * (100 + 273) - 273, 473)
chk('8.21', 'T, К', 350, 350)
chk('8.22', 'm, г', 13.6 * 10 * (573 - 293) / 573, 66.5)
chk('8.23', '|ΔF|, Н', (RHO_AIR - RHO_H2) * g * 800 * (293 - 273) / 293, 642)
chk('8.24', 'ΔF, кН', RHO_AIR * g * 1500 * (293 - 273) / 273 / 1e3, 1.39)
chk('8.25', 'V, см³', (50 - 30) * 0.1 * 273 / (278 - 273) - 30 * 0.1, 106)
# 8.26: p0·h1/T1 = (p0 − ρgx)(h1 − x)/T2 — квадратное уравнение
h1, a = 0.40, RHO_W * g
A_, B_, C_ = a, -(P0 + a * h1), P0 * h1 * (1 - 273 / 310)
x = (-B_ - sqrt(B_ * B_ - 4 * A_ * C_)) / (2 * A_)
chk('8.26', 'Δh, см', x * 100, 4.5)
chk('8.26', 'Δh без столба воды, см', h1 * (1 - 273 / 310) * 100, 4.5)
chk('8.27', 'm, кг', 44 * k * 1e6 * 12e-3 / (R * 300), 0.212)
chk('8.28', 'V, м³', 1e3 * R * 400 / 1e6, 3.32)
chk('8.29', 'p, МПа', 10 * R * 500 / (18 * k * 2) / 1e6, 1.16)
chk('8.30', 'T, К', 1.3e6 * 44 * k * 20e-3 / (0.5 * R), 275)
chk('8.31', 'Mr', 12 * R * 309 / 0.7e6 / k, 44)
chk('8.32', 'ρ, кг/м³', 18 * k * 3.55e3 / (R * 300), 2.56e-2)
chk('8.33', 'F, кН', (29 - 2) * k * g * 60e3 * 1600 / (R * 280) / 1e3, 10.9)
chk('8.34', 'm, г', 2 * k * 25e-3 / (R * 290) * 0.4e6 * 1e3, 8.3)
chk('8.35', 'Δm, кг', 2 * k * 1600 / R * (7 / 8 * 100e3 / 290 - 80e3 / 280), 6.16)

# --- смеси газов ---
chk('8.36', 'V, м³', (1 / (28 * k) + 1 / (4 * k)) * R * T0 / P0, 6.42)
chk('8.36', 'V при p0 = 101 кПа', (1 / (28 * k) + 1 / (4 * k)) * R * T0 / 101e3, 6.42)
V = 20 + 44
chk('8.37', "p1', МПа (в книге 0,76)", 2.4 * 20 / V, 0.76)
chk('8.37', "p2', МПа (в книге 1,12)", 1.6 * 44 / V, 1.12)
chk('8.37', 'p, МПа (в книге 1,88)', (2.4 * 20 + 1.6 * 44) / V, 1.88)
chk('8.38', 'p, кПа', (7 / 28 + 1 / 2) * R * 280 / 0.01 / 1e3, 175)
M = 1 / ((1 / 9) / (2 * k) + (8 / 9) / (32 * k))
chk('8.39', 'ρ, кг/м³', M * 100e3 / (R * 300), 0.481)
n1, n2 = 0.2 / 32, 0.8 / 28
chk('8.40', 'p1, МПа', n1 / (n1 + n2), 0.18)
chk('8.40', 'p2, МПа', n2 / (n1 + n2), 0.82)
chk('8.41', 'Mr воздуха', 1 / (0.232 / 32 + 0.768 / 28), 28.9)
nu = 828e3 * 30e-3 / (R * 300)
m2 = (24 - 2 * nu) / (1 - 2 / 4)    # m1/2 + m2/4 = ν, m1 + m2 = 24 (в граммах, M в г/моль)
chk('8.42', 'm1, г', 24 - m2, 16, 0.01)
chk('8.42', 'm2, г', m2, 8, 0.02)
m = 200e3 * 15e-3 / ((0.7 / (28 * k) + 0.3 / (2 * k)) * R * (23 + 273)) * 1e3
chk('8.43', 'm, г (в книге 6,87)', m, 6.87)
chk('8.43', 'm1, г', 0.7 * m, 4.81)
chk('8.43', 'm2, г', 0.3 * m, 2.06)
chk('8.43', 'm при T = 300 К, г', 200e3 * 15e-3 / ((0.7 / (28 * k) + 0.3 / (2 * k)) * R * 300) * 1e3, 6.87)
chk('8.44', 'T, К', 600e3 * 5e-3 / ((0.6 / (4 * k) + 0.4 / (2 * k)) * 4e-3 * R), 259)
chk('8.45', 'ν1, ммоль', 0.6 * 3.6 / 32 * 1e3, 67.5)
chk('8.45', 'ν2, моль', 0.4 * 3.6 / 2, 0.720)
chk('8.45', 'ν, моль', 0.6 * 3.6 / 32 + 0.4 * 3.6 / 2, 0.788)

for no, what, ours, book, mark in rows:
    print(f'{mark} {no:5} {what:30} наш {ours:12.5g}   книга {book:.4g}')
print('\nрасхождений ≠:', sum(r[4] == '≠' for r in rows), ' в последней цифре ≈:', sum(r[4] == '≈' for r in rows), ' всего строк:', len(rows))
