def chk(no, what, ours, book, tol=0.005):
    if abs(ours - book) > tol * max(abs(book), 1e-300):
        mark = '≠'
    else:
        s = f'{book:.6g}'
        mant = s.split('e')[0]
        dec = len(mant.split('.')[1]) if '.' in mant else 0
        e = int(s.split('e')[1]) if 'e' in s else 0
        r = round(ours / 10**e, dec) * 10**e
        mark = ' ' if abs(r - book) <= 1e-9 * max(abs(book), 1e-300) else '≈'
    rows.append((no, what, ours, book, mark))


def charges_energy(A, B):
    """Энергия взаимодействия двух наборов зарядов [(q, x, y)]."""
    return sum(K * q1 * q2 / sqrt((x1 - x2)**2 + (y1 - y2)**2) for q1, x1, y1 in A for q2, x2, y2 in B)


def field(ch, x, y):
    Ex = Ey = 0.0
    for q, a, b in ch:
        r = sqrt((x - a)**2 + (y - b)**2)
        Ex += K * q * (x - a) / r**3
        Ey += K * q * (y - b) / r**3
    return sqrt(Ex**2 + Ey**2)


def pot(ch, x, y):
    return sum(K * q / sqrt((x - a)**2 + (y - b)**2) for q, a, b in ch)


def cm(alpha_n):          # Клаузиус–Мосотти: ε по αn
    return (3 + 2 * alpha_n) / (3 - alpha_n)


